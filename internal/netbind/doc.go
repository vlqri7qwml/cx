// Package netbind 解决一个 TUN 全局代理必须解决的循环问题：
// 当 0.0.0.0/1 与 128.0.0.0/1 已经指向 TUN 之后，CXProxy 自己到 SOCKS5
// 代理服务器的连接如果走系统默认路由，就会被自己的 TUN 吸进去，
// 形成死循环（流量进协议栈 → 再发给代理 → 又进协议栈）。
//
// 解决办法是把这些 socket 用 IP_UNICAST_IF 绑定到物理网卡上，
// 绕过路由表选路。本包负责：
//
//   - 探测当前物理默认网卡（排除自家 TUN）；
//   - 提供绑定该网卡的 net.Dialer；
//   - 监听路由/接口变化，在 Wi-Fi 与有线之间切换时自动跟随；
//   - 用物理网卡原有的 DNS 直接解析代理服务器域名（代理地址写成域名时需要，
//     此时还不能用走代理的 DNS，否则又是循环依赖）。
//
// 本包仅在 Windows 下有实现。
